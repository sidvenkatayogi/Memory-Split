"""The optimal (GPT-5.6-sol) retriever for the Memory-Split PoC.

The split arm is trained to *ask* an external store for fact values (LMLM
loss-masking); at eval time `evals.generate.generate_batch_with_stats`
intercepts every ``<|db_start|>{query}<|db_retrieve|>`` the model emits and
force-injects whatever `organizer.lookup(query)` returns as the answer text.
Any object exposing ``lookup(str) -> str | None`` is a drop-in retriever.

This module supplies an *optimal* one whose golden knowledge is generated by
**GPT-5.6-sol** through the TrueFoundry OpenAI-compatible gateway. Because the
facts are real Wikidata triples (PopQA), a frontier model genuinely knows the
answers, so the oracle is legitimately near-optimal — and we report its
agreement with the PopQA gold ("fidelity") so the claim stays honest.

Two pieces:
- `GatewayClient` — thin `openai` SDK wrapper (base_url + token from env),
  one `answer(question) -> str` call with retry/backoff. `openai` is imported
  lazily so this module imports offline (tests use a mock client).
- `GPTOracle` — per-eval-item retriever: `lookup(query)` returns that item's
  golden value for ANY query. Returning the right value regardless of the
  model's emitted key is exactly what makes retrieval *optimal* (it removes the
  address-construction confound the real system is still stuck on).

`generate_golden_knowledge` pre-generates + caches one golden value per eval
item so the (paid, networked) GPT calls happen once, not per training run.
"""

from __future__ import annotations

import json
import time
from dataclasses import dataclass
from pathlib import Path

from organizer.store import normalize

DEFAULT_BASE_URL = "https://tfy.promptlens.trilogy.com/v1"
DEFAULT_MODEL = "openai-group/gpt-5.6-sol"

_SYSTEM_PROMPT = (
    "You are a precise knowledge base. Answer the question with ONLY the "
    "factual value (a name, place, date, or short phrase) — no sentence, no "
    "explanation, no punctuation beyond what the value itself needs. If it is "
    "a person, give their full name. Answer with the single most standard/"
    "canonical form."
)


def default_model() -> str:
    import os

    return os.environ.get("POC_GPT_MODEL", DEFAULT_MODEL)


def clean_value(text: str) -> str:
    """Reduce a model reply to a concise injectable value: first non-empty
    line, stripped of surrounding quotes/whitespace and a trailing period."""
    if not text:
        return ""
    line = next((ln.strip() for ln in text.splitlines() if ln.strip()), "")
    line = line.strip().strip('"').strip("'").strip()
    return line.removesuffix(".").strip()


def answer_matches(pred: str, possible_answers) -> bool:
    """True if the prediction agrees with any accepted answer (alias-tolerant),
    using the organizer's normalize (lowercase + whitespace-collapse). Mirrors
    the answer check in evals/keyguess.py: substring in either direction."""
    if not pred:
        return False
    np_ = normalize(pred)
    for a in possible_answers or []:
        na = normalize(a)
        if na and (na == np_ or na in np_ or np_ in na):
            return True
    return False


class GatewayClient:
    """OpenAI-compatible client pointed at the TrueFoundry gateway.

    Reads OPENAI_API_KEY / OPENAI_BASE_URL from the environment (the SDK's
    defaults); `model` defaults to POC_GPT_MODEL or gpt-5.6-sol. `openai` is
    imported lazily so importing this module never requires the SDK.
    """

    def __init__(self, model: str | None = None, base_url: str | None = None,
                 api_key: str | None = None, max_tokens: int = 64,
                 temperature: float = 0.0, max_retries: int = 4):
        import os

        from openai import OpenAI

        self.model = model or default_model()
        self.max_tokens = max_tokens
        self.temperature = temperature
        self.max_retries = max_retries
        self._client = OpenAI(
            api_key=api_key or os.environ.get("OPENAI_API_KEY"),
            base_url=base_url or os.environ.get("OPENAI_BASE_URL", DEFAULT_BASE_URL),
        )

    def answer(self, question: str) -> str:
        last_err: Exception | None = None
        for attempt in range(self.max_retries):
            try:
                resp = self._client.chat.completions.create(
                    model=self.model,
                    messages=[
                        {"role": "system", "content": _SYSTEM_PROMPT},
                        {"role": "user", "content": question},
                    ],
                    temperature=self.temperature,
                    max_tokens=self.max_tokens,
                )
                return clean_value(resp.choices[0].message.content or "")
            except Exception as err:  # noqa: BLE001 - surface after retries
                last_err = err
                time.sleep(min(2 ** attempt, 8))
        raise RuntimeError(
            f"gateway call failed after {self.max_retries} retries: {last_err}"
        )

    def smoke(self, question: str = "What is the capital of France?") -> str:
        """One call to confirm creds/model path end-to-end."""
        return self.answer(question)


class GPTOracle:
    """Per-item optimal retriever: returns this item's golden value for any
    emitted query (robust to imperfect address construction — the whole point
    of assuming an optimal retriever). `value=None` behaves like a miss."""

    __slots__ = ("value",)

    def __init__(self, value: str | None):
        self.value = value

    def lookup(self, query: str) -> str | None:  # noqa: ARG002 - query ignored by design
        return self.value


@dataclass
class GoldenSet:
    """Result of golden-knowledge generation.

    `by_qid` maps eval qid -> the value to inject as the optimal-retriever
    output. `fidelity` is the fraction of items where GPT's own answer agreed
    with the PopQA gold (how optimal GPT-5.6-sol actually was). `rows` is the
    full per-item record (also written to the cache jsonl).
    """

    by_qid: dict[str, str]
    fidelity: float
    n: int
    rows: list[dict]


def _read_cache(path: Path) -> dict[str, dict]:
    cache: dict[str, dict] = {}
    if path.exists():
        with open(path) as f:
            for line in f:
                line = line.strip()
                if line:
                    row = json.loads(line)
                    cache[row["qid"]] = row
    return cache


def generate_golden_knowledge(
    items,
    client,
    cache_path: str | Path,
    ground_truth_fallback: bool = False,
) -> GoldenSet:
    """Generate (and cache) one golden value per eval item via `client.answer`.

    `client` is any object with ``answer(question) -> str`` (GatewayClient in
    production, a mock offline). Already-cached qids are not re-queried, so the
    networked calls happen once. When `ground_truth_fallback` is True, the
    injected value falls back to the PopQA gold whenever GPT disagrees with it,
    yielding the exact upper-bound oracle; otherwise GPT's own answer is
    injected (literally "golden knowledge generated by GPT-5.6-sol").
    """
    cache_path = Path(cache_path)
    cache_path.parent.mkdir(parents=True, exist_ok=True)
    cache = _read_cache(cache_path)

    rows: list[dict] = []
    for it in items:
        meta = it.meta if hasattr(it, "meta") else it["meta"]
        qid = it.qid if hasattr(it, "qid") else it["qid"]
        question = meta.get("question") or _question_from_prompt(it)
        gold_obj = meta["obj"]
        possible = meta.get("possible_answers") or [gold_obj]

        cached = cache.get(qid)
        if cached is not None and "gpt_answer" in cached:
            gpt_answer = cached["gpt_answer"]
        else:
            gpt_answer = clean_value(client.answer(question))

        matched = answer_matches(gpt_answer, possible)
        injected = gpt_answer
        if ground_truth_fallback and not matched:
            injected = gold_obj
        rows.append({
            "qid": qid,
            "question": question,
            "subj": meta.get("subj"),
            "prop": meta.get("prop"),
            "gold_obj": gold_obj,
            "possible_answers": list(possible),
            "gpt_answer": gpt_answer,
            "matched_gold": matched,
            "injected": injected,
            "split": meta.get("split"),
        })

    with open(cache_path, "w") as f:
        for row in rows:
            f.write(json.dumps(row) + "\n")

    n = len(rows)
    fidelity = (sum(1 for r in rows if r["matched_gold"]) / n) if n else 0.0
    return GoldenSet(
        by_qid={r["qid"]: r["injected"] for r in rows},
        fidelity=fidelity,
        n=n,
        rows=rows,
    )


def load_golden_knowledge(cache_path: str | Path) -> dict[str, str]:
    """Load {qid -> injected value} from a cache written by
    `generate_golden_knowledge` (for eval-only reruns without GPT calls)."""
    return {qid: row["injected"] for qid, row in _read_cache(Path(cache_path)).items()}


def _question_from_prompt(item) -> str:
    prompt = item.prompt if hasattr(item, "prompt") else item["prompt"]
    q = prompt
    if q.startswith("Question: "):
        q = q[len("Question: "):]
    return q.split("\nReasoning:", 1)[0].strip()
