"""Reason-over-facts eval: compositional questions whose answer is NOT any
single retrieved fact (so it requires combining facts), evaluated in-context.

We anchor each item to a pair of real PopQA facts sharing a relation and ask a
comparison question ("Do A and B have the same {relation}?"). The gold answer
(yes/no) is computed deterministically from the two facts — reliable ground
truth — while the natural-language phrasing can be generated by GPT-5.6-sol
(template fallback offline). At eval time BOTH models get the two facts in the
prompt context (RAG) and must reason to the answer; this reuses the trained
checkpoints (no retraining) and tests reasoning capacity given identical facts.

Answers are yes/no, so grading is a deterministic keyword check — no judge
needed here (the GPT judge in evals.gpt_oracle is for free-form fact-QA answers).
"""

from __future__ import annotations

import json
import random
import re
from pathlib import Path

from evals.generate import generate_batch_with_stats


def _by_prop(facts) -> dict[str, list[tuple[str, str]]]:
    out: dict[str, list[tuple[str, str]]] = {}
    for f in facts:
        out.setdefault(f.prop, []).append((f.subj, f.obj))
    return out


def make_pairs(facts, n: int, seed: int) -> list[tuple]:
    """Balanced same/different entity pairs sharing a relation.

    Each pair is (prop, subjA, objA, subjB, objB); gold = yes iff objA == objB.
    Bounded (a few pairs per value) so it stays fast on the full fact set.
    """
    rng = random.Random(f"{seed}:reason")
    by_prop = _by_prop(facts)
    matching: list[tuple] = []
    different: list[tuple] = []
    for prop, entries in by_prop.items():
        by_obj: dict[str, list[str]] = {}
        for subj, obj in entries:
            subs = by_obj.setdefault(obj, [])
            if subj not in subs:
                subs.append(subj)
        # same value -> "yes" pairs (cap 3 per value to avoid blowup)
        for obj, subs in by_obj.items():
            for k in range(min(3, len(subs) - 1)):
                matching.append((prop, subs[k], obj, subs[k + 1], obj))
        # different value -> "no" pairs
        objs = list(by_obj)
        if len(objs) >= 2:
            for _ in range(min(50, len(objs) * 2)):
                o1, o2 = rng.sample(objs, 2)
                different.append((prop, rng.choice(by_obj[o1]), o1,
                                  rng.choice(by_obj[o2]), o2))
    rng.shuffle(matching)
    rng.shuffle(different)
    half = min(n // 2, len(matching))
    pairs = matching[:half] + different[: n - half]
    rng.shuffle(pairs)
    return pairs[:n]


_GEN_SYSTEM = (
    "You write a single natural-language yes/no question. Given two facts that "
    "share a relation, ask whether the two subjects have the same value for that "
    "relation. Output ONLY the question, nothing else."
)


def _phrase(client, prop: str, subj_a: str, subj_b: str) -> str:
    template = f"Do {subj_a} and {subj_b} have the same {prop}?"
    if client is None:
        return template
    user = (f"Relation: {prop}\nSubject A: {subj_a}\nSubject B: {subj_b}\n"
            "Question:")
    try:
        text = client.chat(_GEN_SYSTEM, user, max_tokens=40).strip()
        line = next((ln.strip() for ln in text.splitlines() if ln.strip()), "")
        return line or template
    except Exception:  # noqa: BLE001 - phrasing is best-effort; fall back
        return template


def _read_cache(path: Path) -> dict[str, dict]:
    cache: dict[str, dict] = {}
    if path and path.exists():
        with open(path) as f:
            for line in f:
                if line.strip():
                    row = json.loads(line)
                    cache[row["qid"]] = row
    return cache


def generate_reasoning_items(facts, n: int, seed: int,
                             cache_path: str | Path | None = None,
                             client=None) -> list[dict]:
    """Build (and cache) n compositional yes/no items over real fact pairs."""
    cache = _read_cache(Path(cache_path)) if cache_path else {}
    pairs = make_pairs(facts, n, seed)
    items: list[dict] = []
    for i, (prop, sa, oa, sb, ob) in enumerate(pairs):
        qid = f"rsn-{i}"
        cached = cache.get(qid)
        question = cached["question"] if cached else _phrase(client, prop, sa, sb)
        items.append({
            "qid": qid,
            "kind": "same_relation",
            "prop": prop,
            "question": question,
            "answer": "yes" if oa == ob else "no",
            "facts": [[sa, prop, oa], [sb, prop, ob]],
        })
    if cache_path:
        p = Path(cache_path)
        p.parent.mkdir(parents=True, exist_ok=True)
        with open(p, "w") as f:
            for it in items:
                f.write(json.dumps(it) + "\n")
    return items


def reasoning_prompt(item: dict) -> str:
    facts = "\n".join(f"- The {p} of {s} is {o}." for s, p, o in item["facts"])
    return f"Facts:\n{facts}\nQuestion: {item['question']}\nAnswer:"


def grade_yesno(pred: str, gold: str) -> bool:
    """First standalone yes/no token in the generation must match gold."""
    m = re.search(r"\b(yes|no)\b", pred.lower())
    return bool(m) and m.group(1) == gold


def score_reasoning(model, tok, items: list[dict], device,
                    max_new: int = 16, batch_size: int = 16) -> dict:
    """Decode each item RAG-style (facts in context, store OFF) and grade yes/no.
    Also reports the majority-class baseline so a degenerate always-yes/always-no
    model is obvious."""
    prompts = [reasoning_prompt(it) for it in items]
    texts: list[str] = []
    for lo in range(0, len(prompts), batch_size):
        bt, _ = generate_batch_with_stats(
            model, tok, prompts[lo:lo + batch_size], max_new=max_new,
            organizer=None, device=device,
        )
        texts.extend(bt)
    rows = [
        {"qid": it["qid"], "gold": it["answer"], "pred": t[:80].strip(),
         "correct": grade_yesno(t, it["answer"])}
        for it, t in zip(items, texts)
    ]
    n = len(rows)
    acc = sum(r["correct"] for r in rows) / n if n else 0.0
    n_yes = sum(1 for it in items if it["answer"] == "yes")
    majority = max(n_yes, n - n_yes) / n if n else 0.0
    return {"acc": acc, "n": n, "majority_baseline": majority, "rows": rows}
